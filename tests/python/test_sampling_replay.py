"""Seeded execution replays within the current Maestro version.

The case descriptions cover several backends, noisy circuits and checkpoints.
Expected random samples are generated by the current implementation on each
run, rather than frozen to an older Maestro version or compiler.
"""

from copy import deepcopy
import json
import os
from pathlib import Path
import subprocess
import sys

import pytest

import maestro


CASES = json.loads((Path(__file__).with_name("data") / "sampling_replay_cases.json").read_text(encoding="utf-8"))


def _circuit(spec):
    if "qasm" in spec:
        return maestro.QasmToCirc().parse_and_translate(spec["qasm"])
    circuit = maestro.circuits.QuantumCircuit()
    for name, arguments in spec["operations"]:
        getattr(circuit, name)(*arguments)
    return circuit


def _run_case(case, policy):
    config_values = dict(case["config"])
    config_values["simulation_type"] = getattr(maestro.SimulationType, config_values["simulation_type"])
    config_values["counts_policy"] = policy
    config = maestro.SimulatorConfig(**config_values)
    circuit = _circuit(case["circuit"])
    noise = maestro.NoiseModel()
    for name, arguments in case.get("noise", []):
        getattr(noise, name)(*arguments)
    arguments = dict(case["arguments"])
    if case["api"] == "execute":
        return circuit.execute(config=config, **arguments)
    if case["api"] == "execute_suffix":
        checkpoint = maestro.PrefixCheckpointedSimulator(_circuit(case["prefix"]), case["num_qubits"], config)
        return checkpoint.execute_suffix(circuit, noise_model=noise, **arguments)
    return getattr(circuit, case["api"])(noise, config=config, **arguments)


def _fresh_process_results():
    cases = {case["id"]: case for case in CASES}
    results = {}
    for name in (
        "clean_stabilizer_seed_zero",
        "clean_statevector_seed_uint64_max",
        "statevector_dynamic_config_and_noise_seeds",
        "checkpoint_pauli_readout_noise_seed_zero",
    ):
        case = deepcopy(cases[name])
        case["config"]["max_simulators"] = 4
        if name == "clean_statevector_seed_uint64_max":
            case["arguments"]["shots"] = 2048
        result = _run_case(case, "auto")
        assert sum(result["counts"].values()) == case["arguments"]["shots"]
        results[name] = {"counts": result["counts"], "strategy": result.get("sampling_strategy")}
    return results


def _native_library_directories():
    """Folders of the native libraries this process loaded, outside Windows itself.

    A fresh interpreter inherits no os.add_dll_directory registration, which is
    how a build tree's test run usually finds the extension's dependencies. The
    children therefore register the folders this process resolved them from.
    """
    if os.name != "nt":
        return []
    import ctypes
    from ctypes import wintypes

    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    psapi = ctypes.WinDLL("psapi", use_last_error=True)
    kernel32.GetCurrentProcess.restype = wintypes.HANDLE
    kernel32.GetModuleFileNameW.argtypes = [wintypes.HMODULE, wintypes.LPWSTR, wintypes.DWORD]
    kernel32.GetModuleFileNameW.restype = wintypes.DWORD
    psapi.EnumProcessModules.argtypes = [wintypes.HANDLE, ctypes.POINTER(wintypes.HMODULE), wintypes.DWORD, wintypes.LPDWORD]
    psapi.EnumProcessModules.restype = wintypes.BOOL
    process = kernel32.GetCurrentProcess()
    capacity = 1024
    while True:
        modules = (wintypes.HMODULE * capacity)()
        needed = wintypes.DWORD()
        if not psapi.EnumProcessModules(process, modules, ctypes.sizeof(modules), ctypes.byref(needed)):
            raise ctypes.WinError(ctypes.get_last_error())
        count = needed.value // ctypes.sizeof(wintypes.HMODULE)
        if count <= capacity:
            break
        capacity = count
    system = os.path.normcase(os.environ.get("SystemRoot", r"C:\Windows")) + os.sep
    folders = []
    name = ctypes.create_unicode_buffer(32768)
    for module in modules[:count]:
        if module and kernel32.GetModuleFileNameW(module, name, len(name)):
            folder = os.path.dirname(name.value)
            if not os.path.normcase(folder + os.sep).startswith(system) and folder not in folders:
                folders.append(folder)
    return folders


_FRESH_PROCESS_REPLAY = """
import importlib.util
import json
import os
from pathlib import Path
import runpy
import sys

payload = json.load(sys.stdin)
# Dependency folders of the parent's extension (none outside Windows). An
# installed wheel also runs its own package bootstrap below.
dll_handles = [os.add_dll_directory(path) for path in payload["dll_directories"] if os.path.isdir(path)]
spec = importlib.util.spec_from_file_location(
    "maestro", payload["package_file"], submodule_search_locations=payload["package_paths"]
)
maestro = importlib.util.module_from_spec(spec)
sys.modules["maestro"] = maestro
spec.loader.exec_module(maestro)
assert Path(maestro._raw_maestro.__file__).resolve() == Path(payload["extension_file"]).resolve()
suite = runpy.run_path(payload["test_file"])
print(json.dumps(suite["_fresh_process_results"](), sort_keys=True))
"""


def test_seeded_counts_replay_in_fresh_processes():
    expected = _fresh_process_results()
    payload = json.dumps({
        "package_file": maestro.__file__,
        "package_paths": list(maestro.__path__),
        "extension_file": maestro._raw_maestro.__file__,
        "test_file": str(Path(__file__).resolve()),
        "dll_directories": _native_library_directories(),
    })
    for _ in range(2):
        result = subprocess.run(
            [sys.executable, "-c", _FRESH_PROCESS_REPLAY],
            input=payload, capture_output=True, text=True, timeout=60,
        )
        assert result.returncode == 0, result.stderr or result.stdout
        assert json.loads(result.stdout) == expected


@pytest.mark.parametrize("policy", ["auto", "legacy", "frame_v1", "multinomial_v1"])
@pytest.mark.parametrize("case", CASES, ids=lambda case: case["id"])
def test_seeded_counts_replay_current_version(case, policy):
    first = _run_case(case, policy)
    repeated = _run_case(case, policy)
    assert "samples" not in first
    assert first["counts"] == repeated["counts"]
    assert sum(first["counts"].values()) == case["arguments"]["shots"]
    assert first.get("sampling_strategy") == repeated.get("sampling_strategy")
